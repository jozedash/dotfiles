#!/usr/bin/env bash
#
# Set up hibernation to a swapfile on /home. Run as root; safe to run again.
#
#   1. Creates /home/swapfile, sized to RAM, and adds it to /etc/fstab at a low
#      priority, so zram (pri 100) is still used for normal swapping
#   2. Adds resume=UUID=<home> resume_offset=<offset> to the kernel command line:
#      the systemd-boot entries, or /etc/default/grub (each is backed up first)
#   3. Adds the resume hook to the initramfs via /etc/mkinitcpio.conf.d/hibernate.conf,
#      generated from this machine's own HOOKS, and rebuilds it if that changed
#
# None of this is in git: the UUID, offset and HOOKS are specific to each machine.
# logind also needs to see /home: etc/systemd/system/systemd-logind.service.d/.

SWAPFILE=/home/swapfile

if [ "$EUID" -ne 0 ]; then
    echo "Run as root"
    exit 1
fi
set -e

# filefrag's offsets are only what the kernel needs on ext4/xfs (btrfs is different)
FSTYPE=$(findmnt -no FSTYPE -T "$(dirname "$SWAPFILE")")
if [ "$FSTYPE" != ext4 ] && [ "$FSTYPE" != xfs ]; then
    echo "$(dirname "$SWAPFILE") is $FSTYPE; this script only handles ext4 and xfs"
    exit 1
fi

# RAM rounded up to a multiple of 4 GiB (16 GB of RAM shows up as ~15 GiB)
RAM_KB=$(awk '/^MemTotal/ {print $2}' /proc/meminfo)
SIZE_G=$(( (RAM_KB + 4*1024*1024 - 1) / (4*1024*1024) * 4 ))

if [ ! -f "$SWAPFILE" ]; then
    FREE_G=$(df --output=avail -BG "$(dirname "$SWAPFILE")" | tail -1 | tr -dc 0-9)
    if [ "$FREE_G" -lt $((SIZE_G + 5)) ]; then
        echo "Not enough space for a ${SIZE_G}G swapfile (${FREE_G}G free)"
        exit 1
    fi
    echo "Creating ${SIZE_G}G $SWAPFILE"
    mkswap --file "$SWAPFILE" --size "${SIZE_G}G"
else
    echo "$SWAPFILE already exists"
fi

if ! grep -q "^$SWAPFILE " /etc/fstab; then
    echo "Adding $SWAPFILE to /etc/fstab"
    echo "$SWAPFILE none swap defaults,pri=0 0 0" >> /etc/fstab
fi
swapon --show=NAME --noheadings | grep -qx "$SWAPFILE" || swapon --priority 0 "$SWAPFILE"

UUID=$(findmnt -no UUID -T "$SWAPFILE")
OFFSET=$(filefrag -v "$SWAPFILE" | awk '$1=="0:" {print substr($4,1,length($4)-2)}')
if [ -z "$UUID" ] || [ -z "$OFFSET" ]; then
    echo "Couldn't find the UUID ($UUID) or offset ($OFFSET) of $SWAPFILE"
    exit 1
fi
RESUME="resume=UUID=$UUID resume_offset=$OFFSET"
echo "Resume parameters: $RESUME"

# No colons: /boot may be FAT
STAMP=$(date '+%Y-%m-%d_%H%M%S')
if compgen -G '/boot/loader/entries/*.conf' > /dev/null; then
    for ENTRY in /boot/loader/entries/*.conf; do
        if grep -q "^options.* $RESUME\b" "$ENTRY"; then
            echo "Already set: $ENTRY"
            continue
        fi
        cp "$ENTRY" "$ENTRY.bak-$STAMP"
        # Drop any older resume settings (e.g. the swapfile was recreated), then append
        sed -i -E -e '/^options/ s/ resume(_offset)?=[^ ]*//g' -e "/^options/ s/\$/ $RESUME/" "$ENTRY"
        echo "Updated $ENTRY (backup: $ENTRY.bak-$STAMP)"
    done
elif [ -f /etc/default/grub ] && command -v grub-mkconfig > /dev/null; then
    if grep -q "^GRUB_CMDLINE_LINUX_DEFAULT=.*$RESUME\b" /etc/default/grub; then
        echo "Already set: /etc/default/grub"
    else
        cp /etc/default/grub "/etc/default/grub.bak-$STAMP"
        sed -i -E -e '/^GRUB_CMDLINE_LINUX_DEFAULT=/ s/ ?resume(_offset)?=[^ "]*//g' \
            -e "/^GRUB_CMDLINE_LINUX_DEFAULT=/ s/\"\$/ $RESUME\"/" /etc/default/grub
        grub-mkconfig -o /boot/grub/grub.cfg
        echo "Updated /etc/default/grub (backup: /etc/default/grub.bak-$STAMP)"
    fi
else
    echo "Unknown boot loader (not systemd-boot or GRUB): add '$RESUME' to the kernel command line by hand"
    exit 1
fi

# The resume hook goes after filesystems. Initramfs images built with the
# systemd hook resume on their own and need nothing.
CONF=/etc/mkinitcpio.conf.d/hibernate.conf
HOOKS=$(
    . /etc/mkinitcpio.conf
    for f in /etc/mkinitcpio.conf.d/*.conf; do
        [ -f "$f" ] && [ "$f" != "$CONF" ] && . "$f"
    done
    echo "${HOOKS[*]}"
)
if [[ " $HOOKS " == *" systemd "* ]] || [[ " $HOOKS " == *" resume "* ]]; then
    NEW=""
else
    NEW="# Generated by setup/hibernate.sh: this machine's HOOKS plus resume
HOOKS=($(sed 's/\bfilesystems\b/filesystems resume/' <<< "$HOOKS"))"
fi

if [ "$NEW" != "$(cat "$CONF" 2>/dev/null)" ]; then
    if [ -n "$NEW" ]; then
        mkdir -p "$(dirname "$CONF")"
        echo "$NEW" > "$CONF"
        echo "Wrote $CONF"
    else
        rm -f "$CONF"
    fi
    mkinitcpio -P
else
    echo "Initramfs already has resume support"
fi
